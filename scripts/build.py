"""Build and validate the reading lists using only the Python standard library."""
import argparse
from datetime import date
import html
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit
from site_builder import render_site

ROOT = Path(__file__).resolve().parents[1]
TYPES = {'paper', 'survey', 'system', 'perspective', 'dataset', 'benchmark', 'infrastructure', 'method', 'project'}
STATUSES = {'primary-record-checked', 'primary-page-checked', 'primary-manuscript-checked', 'project-link-unresolved'}
LABELS = {name: name.capitalize() for name in TYPES}


def ordered(entries):
    return sorted(entries, key=lambda e: (-(e['year'] or 0), e['title'].casefold(), e['id']))


def validate(data):
    assert data['schema_version'] == 2, 'Unsupported catalogue schema'
    updated = date.fromisoformat(data['updated'])
    assert updated <= date.today(), 'Update date is in the future'
    assert 'categories' not in data, 'Catalogue uses year-only organization'
    ids, identities, titles = set(), set(), set()
    for e in data['entries']:
        ident = e['id']
        assert re.fullmatch(r'[rn]\d{3}', ident), f'Invalid ID: {ident}'
        assert ident not in ids, f'Duplicate ID: {ident}'
        ids.add(ident)
        assert 'category' not in e, f'{ident}: category fields are not used'
        assert e['resource_type'] in TYPES, f'{ident}: unknown resource type'
        assert e['year_basis'] in {'first-preprint', 'record-year', 'maintainer-provided', 'undated-project'}
        year = e['year']
        assert (isinstance(year, int) and not isinstance(year, bool) and 1900 <= year <= updated.year) or (year is None and e['resource_type'] == 'project'), f'{ident}: invalid year'
        assert (year is None) == (e['year_basis'] == 'undated-project'), f'{ident}: inconsistent date basis'
        for key in ('title', 'summary', 'url'):
            assert isinstance(e[key], str) and e[key].strip(), f'{ident}: empty {key}'
            assert '\n' not in e[key], f'{ident}: multiline {key}'
        normalized_title = re.sub(r'[^\w]', '', e['title'].casefold())
        assert normalized_title not in titles, f'{ident}: duplicate title'
        titles.add(normalized_title)
        for key in ('url', 'related_url'):
            if key not in e:
                continue
            parsed = urlsplit(e[key])
            assert parsed.scheme == 'https' and parsed.netloc, f'{ident}: invalid HTTPS URL'
            assert not parsed.username and not parsed.password, f'{ident}: URL credentials'
            assert not re.search(r'xxxxx|localhost|127\.0\.0\.1', e[key]), f'{ident}: placeholder URL'
        identity = re.sub(r'v\d+$', '', e['url']).rstrip('/')
        assert identity not in identities, f'{ident}: duplicate paper URL'
        identities.add(identity)
        assert e['record_check']['status'] in STATUSES, f'{ident}: unknown check status'
        assert date.fromisoformat(e['record_check']['date']) <= updated, f'{ident}: check date after update'
        assert len(e['summary'].split()) <= 45, f'{ident}: summary is too long'
        assert 'authors' in e or (e['resource_type'] == 'project' and e.get('authors_note')), f'{ident}: missing author list or project explanation'
        if 'authors' in e:
            assert isinstance(e['authors'], list) and e['authors'], f'{ident}: empty author list'
            assert all(isinstance(a, str) and a.strip() == a and a and '\n' not in a for a in e['authors']), f'{ident}: invalid author name'
            assert e['first_author'] == e['authors'][0], f'{ident}: first author differs from author list'
            check = e['authors_check']
            assert date.fromisoformat(check['date']) <= updated, f'{ident}: author check after update'
            assert urlsplit(check['source']).scheme == 'https', f'{ident}: invalid author source'



def entry(e):
    title = html.escape(e['title'], quote=False)
    label = str(e['year']) if e['year'] else 'Undated'
    prefix = f"<a id=\"{e['id']}\"></a>"
    lines = [f"- {prefix}**[{title}]({e['url']})** · {label} · {LABELS[e['resource_type']]}", f"  {e['summary']}"]
    return '\n'.join(lines)


def render(data):
    entries = ordered(data['entries'])
    years = sorted({e['year'] for e in entries if e['year']}, reverse=True)
    periods = years + ([None] if any(e['year'] is None for e in entries) else [])
    lines = [
        '<!-- Generated by scripts/build.py from data/catalog.json. -->',
        '# Awesome Generalist Robotics',
        '',
        '![Awesome Generalist Robotics — shared competence, diverse embodiments](assets/banner.svg)',
        '',
        '**A curated research collection on generalist robot policies, cross-embodiment learning, and unified embodied autonomy.**',
        '',
        'How can robots reuse learned competence across tasks, environments, sensors, and physical bodies? '
        'This collection brings together research on shared policies, reusable representations, morphology-aware control, '
        'world models, and integrated autonomy systems, alongside datasets and benchmarks needed to evaluate them. '
        'It spans manipulation, navigation, locomotion, and multiple robot morphologies, connecting advances in robot foundation models '
        'with the physical constraints and deployment demands of autonomous systems.',
        '',
        f'[Website](https://ntnu-arl.github.io/awesome-generalist-robotics/) · Last curated: {data["updated"]} · [Compact index](docs/by-year.md) · [Scope and curation](docs/curation.md) · [Contribute](CONTRIBUTING.md)',
        '',
        '## How to read this list',
        '',
        'References are organized by **year, newest first**, and alphabetically by title within each year. '
        'Each entry has a primary-source link, year, resource type, and a very short account of its contribution. '
        'Years usually identify the first arXiv release, otherwise they follow the linked publication record. ',
        '',
        '## Contents',
        '',
        '| Year | References |',
        '| :--- | ---: |',
    ]

    for year in periods:
        label = str(year) if year else 'Undated'
        count = sum(e['year'] == year for e in entries)
        lines.append(f'| [{label}](#{label.lower()}) | {count} |')
    for year in periods:
        label = str(year) if year else 'Undated'
        lines.extend(['', f'## {label}', ''])
        lines.append('\n\n'.join(entry(e) for e in entries if e['year'] == year))
        lines.extend(['', '[Back to contents](#contents)'])
    lines.extend([
        '', '## Contributing', '',
        'Suggestions, metadata corrections, and evidence-based scope clarifications are welcome. '
        'Please read [CONTRIBUTING.md](CONTRIBUTING.md), edit the [catalogue](data/catalog.json), and regenerate the lists. '
        'Use the issue forms if you prefer to suggest a reference without editing files.',
        '', '## Curation and acknowledgements', '',
        'This is a selective reading list, not a systematic review or a leaderboard. '
        'Summaries describe research contributions; inclusion is not endorsement or independent replication. '
        'See the [curation notes](docs/curation.md) for coverage and verification limits.',
        '',
        'The initial collection combines an existing robotics literature map with reference discovery through '
        '[Awesome Generalist Agents](https://github.com/cheryyunl/awesome-generalist-agents). '
        'Research credit belongs to the authors of the linked works. Please cite the original papers for scientific claims.',
        '', '## License', '',
        'Original catalogue text, data, and artwork: [CC BY 4.0](LICENSE.md). '
        'Maintenance scripts: [MIT](scripts/LICENSE). Linked publications and software retain their own licenses.',
    ])
    by_year = [
        '<!-- Generated by scripts/build.py from data/catalog.json. -->',
        '# Compact reference index', '', '[Full reading list](../README.md#contents)', '',
        'References are organized by year, newest first, and alphabetically within each year. '
        'Years identify the first arXiv release when available, otherwise the linked publication record. '
        'Conference and proceedings years can differ. Project dates may be maintainer-provided.', '',
    ]
    by_year.append(' · '.join(f'[{str(y) if y else "Undated"}](#{str(y).lower() if y else "undated"})' for y in periods))
    for year in periods:
        by_year.extend(['', f'## {year or "Undated"}', ''])
        for e in entries:
            if e['year'] != year:
                continue
            by_year.append(f"- **[{e['title']}](../README.md#{e['id']})** · {LABELS[e['resource_type']]}")
    by_year.append('')
    return {'README.md': '\n'.join(lines).rstrip()+'\n', 'docs/by-year.md':'\n'.join(by_year), 'index.html': render_site(data)}


def anchors(text):
    found = set(re.findall(r'<a id="([^"]+)"></a>', text))
    for title in re.findall(r'^#{1,6} (.+)$', text, re.M):
        slug = re.sub(r'[^\w\- ]', '', title.casefold()).replace(' ', '-')
        found.add(slug)
    return found


def check_local_links(outputs):
    """Check Markdown paths and anchors without making external network requests."""
    texts = {p.relative_to(ROOT).as_posix():p.read_text() for p in ROOT.rglob('*.md')}
    texts.update(outputs)
    for relative, text in texts.items():
        assert not re.search(r'\[\[|/home/|file://|TODO|YOUR_USERNAME|plugin://', text), f'{relative}: private path, wiki syntax or placeholder'
        for target in re.findall(r'!?\[[^\]\n]*\]\(([^\s)]+)\)', text):
            if urlsplit(target).scheme:
                continue
            path, _, fragment = unquote(target).partition('#')
            resolved = (ROOT / relative).parent / path if path else ROOT / relative
            resolved = resolved.resolve()
            assert resolved.is_relative_to(ROOT.resolve()), f'{relative}: link leaves repository'
            assert resolved.exists() or resolved.relative_to(ROOT).as_posix() in outputs, f'{relative}: missing {target}'
            key = resolved.relative_to(ROOT).as_posix()
            if fragment and key in texts:
                assert fragment in anchors(texts[key]), f'{relative}: broken anchor {target}'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate data and fail if generated lists are stale; write nothing')
    args = parser.parse_args()
    try:
        data = json.loads((ROOT/'data/catalog.json').read_text())
        validate(data)
        outputs = render(data)
        check_local_links(outputs)
        for name, expected in outputs.items():
            path = ROOT/name
            if args.check:
                assert path.exists() and path.read_text() == expected, f'{name} is stale; run python3 scripts/build.py'
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
        print(f"Validated {len(data['entries'])} references in newest-first year order; " + ('generated lists are current.' if args.check else 'reading lists generated.'))
    except (AssertionError, KeyError, ValueError, TypeError) as error:
        print(f'Validation failed: {error}', file=sys.stderr)
        return 1
    return 0

if __name__ == '__main__':
    sys.exit(main())
